export type Lang = 'en' | 'ar';
export const STRINGS: Record<Lang, Record<Key, string>> = { en, ar };

export function dirFor(lang: Lang): 'ltr' | 'rtl' {
  return lang === 'ar' ? 'rtl' : 'ltr';
}

// {n|one:word|other:words} picks the form for n. arabic uses few (3 to 10) and many (11 to 99).
export function format(text: string, vars: Record<string, string | number> = {}, lang: Lang = 'en'): string {
  return text
    .replace(/\{(\w+)\|([^}]+)\}/g, (all, name: string, forms: string) => {
      if (typeof vars[name] !== 'number') return all;
      const pick = Object.fromEntries(forms.split('|').map(f => f.split(':') as [string, string]));
      return pick[new Intl.PluralRules(lang).select(vars[name] as number)] ?? pick.other ?? all;
    })
    .replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all));
}
